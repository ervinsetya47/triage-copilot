#!/usr/bin/env python3
"""Regenerate docs/data.js from the CLI rule files (data/*.json).

The web app embeds the exact same rules the Python CLI uses, so the two
can never silently drift apart. Re-run after editing any rule file:

    python3 tools/build_web_data.py

Then verify both implementations agree:

    python3 triage.py --demo
    node tools/check_web.js
"""

import json
from pathlib import Path

BASE = Path(__file__).resolve().parent.parent
DATA = BASE / "data"
OUT = BASE / "docs" / "data.js"


def load(name):
    with open(DATA / name, encoding="utf-8") as f:
        return json.load(f)


def main():
    scopes = load("scopes.json")["programs"]
    known_issues = load("known_issues.json")["known_issues"]
    disclosures = load("disclosures.json")["disclosures"]
    expected = load("fixtures/expected.json")
    fixtures = {}
    for path in sorted((DATA / "fixtures").glob("*.json")):
        if path.name == "expected.json":
            continue
        with open(path, encoding="utf-8") as f:
            fixtures[path.stem] = json.load(f)

    payload = {
        "scopes": scopes,
        "knownIssues": known_issues,
        "disclosures": disclosures,
        "expected": expected,
        "fixtures": fixtures,
    }
    text = (
        "/* Generated by tools/build_web_data.py from data/*.json — do not edit by hand. */\n"
        "const TRIAGE_DATA = "
        + json.dumps(payload, indent=2, ensure_ascii=False)
        + ";\n\n"
        "if (typeof module !== \"undefined\" && module.exports) {\n"
        "  module.exports = TRIAGE_DATA;\n"
        "}\n"
    )
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(fixtures)} fixtures, "
          f"{len(known_issues)} known issues, {len(disclosures)} disclosures)")


if __name__ == "__main__":
    main()
